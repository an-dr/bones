use super::*;

fn request(kind: Kind) -> Request {
    Request {
        name: "pong".to_string(),
        kind,
        dependencies: Dependencies::tagged(),
        cli: "C:/tools/bones-cli.exe".to_string(),
    }
}

#[test]
fn every_placeholder_is_filled_in_every_kind() {
    for kind in [Kind::Game, Kind::Egui, Kind::Web, Kind::Embed] {
        for (path, contents) in files(&request(kind)) {
            // `{{` alone is ordinary Rust inside format!; a placeholder is a
            // lowercase word between double braces.
            for placeholder in [
                "{{name}}",
                "{{sdk_dep}}",
                "{{test_dep}}",
                "{{kernel_dep}}",
                "{{kind_config}}",
                "{{app_member}}",
            ] {
                assert!(
                    !contents.contains(placeholder),
                    "{kind:?} {path} keeps {placeholder}"
                );
            }
        }
    }
}

#[test]
fn only_embed_has_an_app_and_names_it_a_member() {
    let embed = files(&request(Kind::Embed));
    assert!(embed.iter().any(|(path, _)| *path == "app/src/main.rs"));
    let workspace = &embed
        .iter()
        .find(|(path, _)| *path == "Cargo.toml")
        .unwrap()
        .1;
    assert!(workspace.contains("\"app\""));

    let game = files(&request(Kind::Game));
    assert!(!game.iter().any(|(path, _)| path.starts_with("app/")));
}

#[test]
fn the_web_kind_turns_web_panels_on() {
    let web = files(&request(Kind::Web));
    let config = &web
        .iter()
        .find(|(path, _)| *path == "bones.toml")
        .unwrap()
        .1;
    assert!(config.contains("web = true"));
}

#[test]
fn names_must_work_as_crate_and_extension_names() {
    assert!(is_crate_name("pong"));
    assert!(is_crate_name("pong-2_d"));
    assert!(!is_crate_name("Pong"));
    assert!(!is_crate_name("2pong"));
    assert!(!is_crate_name("my pong"));
}

#[test]
fn a_verbatim_windows_path_is_stripped() {
    assert_eq!(
        strip_verbatim(Path::new(r"\\?\C:\code\bones")),
        PathBuf::from(r"C:\code\bones")
    );
}

#[test]
fn the_mcp_config_names_the_cli_that_wrote_it() {
    let files = files(&request(Kind::Game));
    let mcp = &files
        .iter()
        .find(|(path, _)| *path == ".mcp.json")
        .unwrap()
        .1;
    assert!(mcp.contains("C:/tools/bones-cli.exe"), "{mcp}");
}

#[test]
fn agents_md_is_the_plugin_rules_with_their_source() {
    let files = files(&request(Kind::Game));
    let agents = &files
        .iter()
        .find(|(path, _)| *path == "AGENTS.md")
        .unwrap()
        .1;
    assert!(agents.starts_with("<!-- Generated by bones-cli from the bones-user agent plugin"));
    assert!(agents.ends_with(RULES));
}

#[test]
fn the_project_mcp_config_is_the_plugin_server_in_project_form() {
    let mcp: serde_json::Value = serde_json::from_str(&project_mcp("C:/x/bones-cli.exe")).unwrap();
    assert!(mcp.get("$schema").is_none());
    assert_eq!(mcp["mcpServers"]["bones"]["command"], "C:/x/bones-cli.exe");
    assert_eq!(mcp["mcpServers"]["bones"]["args"][0], "mcp");
}
