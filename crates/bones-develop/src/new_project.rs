//! `bones-develop new`: writes a project that builds and passes its checks.

use std::path::{Path, PathBuf};

use crate::dependencies::Dependencies;
use crate::kind::Kind;
use crate::source::Source;
use crate::{engines, home, repository, submodule, Result};

const USAGE: &str =
    "usage: bones-develop new <name> [--kind game|egui|web|embed] [--tag <tag>] [--submodule [<path>] | --bones-path <checkout>]";

const WORKSPACE: &str = include_str!("../templates/common/workspace.Cargo.toml");
const EXTENSION_MANIFEST: &str = include_str!("../templates/common/extension.Cargo.toml");
const CHECKS_MANIFEST: &str = include_str!("../templates/common/checks.Cargo.toml");
const CONFIG: &str = include_str!("../templates/common/bones.toml");
/// The product rules of the `bones-user` agent plugin, its single source:
/// a project's `AGENTS.md` is generated from them.
/// Where they live in a checkout.
pub const RULES_PATH: &str = "agent-plugins/bones-user/skills/bones/references/rules.md";
pub const PLUGIN_MCP_PATH: &str = "agent-plugins/bones-user/mcp.json";
pub const RULES: &str =
    include_str!("../../../agent-plugins/bones-user/skills/bones/references/rules.md");
/// The plugin's MCP servers, from which a project's `.mcp.json` is made.
pub const PLUGIN_MCP: &str = include_str!("../../../agent-plugins/bones-user/mcp.json");
const GITIGNORE: &str = include_str!("../templates/common/gitignore");

pub fn run(args: &[String]) -> Result {
    let request = Request::parse(args)?;
    let root = PathBuf::from(&request.name);
    // With --submodule, parsing made the folder to hold the submodule.
    if root.exists() && !request.created {
        return Err(format!(
            "{} already exists; choose another name or remove it",
            root.display()
        ));
    }
    for (path, contents) in files(&request) {
        let path = root.join(path);
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|error| format!("creating {}: {error}", parent.display()))?;
        }
        std::fs::write(&path, contents)
            .map_err(|error| format!("writing {}: {error}", path.display()))?;
    }
    println!(
        "Created {} ({:?}, {}).",
        root.display(),
        request.kind,
        request.pin
    );
    println!();
    println!("  cd {}", request.name);
    println!("  bones-develop dev      # run it, hot-reloading on every save");
    println!("  cargo test         # the headless checks");
    Ok(())
}

/// Every file of the project, relative to its root, with placeholders filled.
fn files(request: &Request) -> Vec<(&'static str, String)> {
    let template = |(path, compiled): (&str, &str)| {
        let text = match &request.source {
            Some(source) => source.template(path, compiled),
            None => compiled.to_string(),
        };
        request.fill(&text)
    };
    let plugin = |path: &str, compiled: &str| match &request.source {
        Some(source) => source.read(path, compiled),
        None => compiled.to_string(),
    };
    let mut files = vec![
        (
            "Cargo.toml",
            excluding(
                &template(("common/workspace.Cargo.toml", WORKSPACE)),
                request.vendored.as_deref(),
            ),
        ),
        ("bones.toml", template(("common/bones.toml", CONFIG))),
        ("AGENTS.md", agents_md(&plugin(RULES_PATH, RULES))),
        (
            ".mcp.json",
            project_mcp(&plugin(PLUGIN_MCP_PATH, PLUGIN_MCP), &request.cli),
        ),
        (".gitignore", template(("common/gitignore", GITIGNORE))),
        (
            "extension/Cargo.toml",
            template(("common/extension.Cargo.toml", EXTENSION_MANIFEST)),
        ),
        ("extension/src/lib.rs", template(request.kind.extension())),
        (
            "checks/Cargo.toml",
            template(("common/checks.Cargo.toml", CHECKS_MANIFEST)),
        ),
        ("checks/tests/extension.rs", template(request.kind.check())),
    ];
    if let Some([manifest, main]) = request.kind.app() {
        files.push(("app/Cargo.toml", template(manifest)));
        files.push(("app/src/main.rs", template(main)));
    }
    files
}

/// The project's `AGENTS.md`: the plugin's rules, under a line saying where
/// they come from and where the rest of the plugin is.
pub fn agents_md(rules: &str) -> String {
    format!(
        "<!-- Generated by bones-develop from the bones-user agent plugin (agent-plugins/bones-user in the bones repository); its skill and MCP server go further. -->\n\n{rules}"
    )
}

/// The project's `.mcp.json`: the plugin's servers in the form clients read
/// from a project, with `command` set to this `bones-develop`, wherever
/// cargo installed it.
pub fn project_mcp(plugin_mcp: &str, cli: &str) -> String {
    // A checkout's file that does not parse falls back to the compiled copy.
    let plugin: serde_json::Value = serde_json::from_str(plugin_mcp)
        .or_else(|_| serde_json::from_str(PLUGIN_MCP))
        .expect("the plugin's mcp.json is valid JSON");
    let mut servers = plugin["mcpServers"].clone();
    for server in servers
        .as_object_mut()
        .into_iter()
        .flat_map(|s| s.values_mut())
    {
        // Tags before the rename name the tool bones-cli.
        if server["command"] == "bones-develop" || server["command"] == "bones-cli" {
            server["command"] = serde_json::json!(cli);
        }
    }
    let mut text = serde_json::to_string_pretty(&serde_json::json!({ "mcpServers": servers }))
        .expect("JSON serialises");
    text.push('\n');
    text
}
// Private to this file: the parsed command line, never named outside it
// (docs/code-style.md's exception).
/// What `bones-develop new` was asked for.
struct Request {
    name: String,
    kind: Kind,
    dependencies: Dependencies,
    /// The checkout the project's files come from: the tag's source, or the
    /// local checkout; `None` uses the compiled-in copies.
    source: Option<Source>,
    /// What the project pins, for the summary: a tag or a path.
    pin: String,
    /// Whether parsing already created the project folder, for a submodule.
    created: bool,
    /// The submodule's path, which the workspace must exclude: cargo makes
    /// every path dependency inside a workspace's folder one of its members.
    vendored: Option<String>,
    /// This `bones-develop`, for `.mcp.json`.
    cli: String,
}

impl Request {
    fn parse(args: &[String]) -> Result<Self> {
        let mut args = args.iter();
        let name = args.next().ok_or_else(|| USAGE.to_string())?.clone();
        if !is_crate_name(&name) {
            return Err(format!(
                "'{name}' is not a usable name: use lowercase letters, digits, and - or _, starting with a letter"
            ));
        }
        let mut kind = Kind::Game;
        let mut tag = None;
        let mut checkout = None;
        let mut vendored = None;
        let mut args = args.peekable();
        while let Some(arg) = args.next() {
            if arg == "--submodule" {
                let path = args.next_if(|value| !value.starts_with("--"));
                vendored = Some(path.cloned().unwrap_or_else(|| "bones".to_string()));
                continue;
            }
            let value = args.next().ok_or_else(|| USAGE.to_string())?;
            match arg.as_str() {
                "--kind" => kind = Kind::parse(value).ok_or_else(|| USAGE.to_string())?,
                "--tag" => tag = Some(value.clone()),
                "--bones-path" => {
                    let path = Path::new(value)
                        .canonicalize()
                        .map_err(|error| format!("{value}: {error}"))?;
                    checkout = Some(strip_verbatim(&path));
                }
                _ => return Err(USAGE.to_string()),
            }
        }
        let mut created = false;
        let vendored_path = vendored.clone();
        let (dependencies, source, pin) = match (checkout, tag) {
            (Some(_), _) if vendored.is_some() => {
                return Err("--submodule and --bones-path exclude each other".into())
            }
            (Some(_), Some(_)) => return Err("--tag and --bones-path exclude each other".into()),
            (None, tag) if vendored.is_some() => {
                let path = vendored.unwrap_or_default();
                let tag = match tag {
                    Some(tag) => tag,
                    None => newest_tag()?,
                };
                let root = PathBuf::from(&name);
                if root.exists() {
                    return Err(format!(
                        "{} already exists; choose another name or remove it",
                        root.display()
                    ));
                }
                std::fs::create_dir_all(&root)
                    .map_err(|error| format!("creating {}: {error}", root.display()))?;
                created = true;
                submodule::ensure_repository(&root)?;
                let checkout = submodule::add(&root, &path, &repository::url(), &tag)?;
                // Path dependencies resolve from each crate's folder, one below the root.
                (
                    Dependencies::local(&Path::new("..").join(&path)),
                    Source::at(&checkout),
                    format!("{tag} in the submodule {path}"),
                )
            }
            (Some(checkout), None) => (
                Dependencies::local(&checkout),
                Source::at(&checkout),
                checkout.display().to_string(),
            ),
            (None, tag) => {
                let tag = match tag {
                    Some(tag) => tag,
                    None => newest_tag()?,
                };
                let source =
                    Source::at(&engines::source(&home::home()?, &repository::url(), &tag)?);
                let abi = source.abi()?;
                (Dependencies::tagged(&tag, &abi), source, tag)
            }
        };
        let cli = std::env::current_exe()
            .map(|exe| strip_verbatim(&exe).to_string_lossy().replace('\\', "/"))
            .unwrap_or_else(|_| "bones-develop".to_string());
        Ok(Self {
            name,
            kind,
            dependencies,
            source: Some(source),
            pin,
            created,
            vendored: vendored_path,
            cli,
        })
    }

    fn fill(&self, template: &str) -> String {
        let app_member = match self.kind.app() {
            Some(_) => ", \"app\"",
            None => "",
        };
        template
            .replace("{{name}}", &self.name)
            .replace("{{sdk_dep}}", &self.dependencies.sdk)
            .replace("{{test_dep}}", &self.dependencies.test)
            .replace("{{kernel_dep}}", &self.dependencies.kernel)
            .replace("{{kind_config}}", self.kind.config())
            .replace("{{app_member}}", app_member)
    }
}

/// The workspace manifest with `vendored` excluded, so the submodule's
/// crates stay members of bones' own workspace.
fn excluding(workspace: &str, vendored: Option<&str>) -> String {
    let Some(path) = vendored else {
        return workspace.to_string();
    };
    let exclude = format!("exclude = [\"{}\"]", path.replace('\\', "/"));
    let mut lines: Vec<String> = workspace.lines().map(str::to_string).collect();
    match lines.iter().position(|line| line.starts_with("members")) {
        Some(at) => lines.insert(at + 1, exclude),
        None => lines.push(exclude),
    }
    lines.join(
        "
",
    ) + "
"
}

/// The repository's newest release tag: a pre-release such as `v3.2.0-rc.1`
/// is taken only when named with `--tag`.
pub fn newest_tag() -> Result<String> {
    newest_release(engines::remote_tags()?)
        .ok_or_else(|| format!("{} has no v* release tags; pass --tag", repository::url()))
}

/// The last of `tags`, sorted oldest first, that is a plain `vX.Y.Z`.
fn newest_release(tags: Vec<String>) -> Option<String> {
    tags.into_iter().rev().find(|tag| {
        let parts: Vec<_> = tag.trim_start_matches('v').split('.').collect();
        tag.starts_with('v')
            && parts.len() == 3
            && parts
                .iter()
                .all(|part| !part.is_empty() && part.bytes().all(|b| b.is_ascii_digit()))
    })
}

/// Whether `name` is a valid package name that is also a valid extension
/// name: the `.wasm` stem becomes the bus endpoint.
fn is_crate_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next().is_some_and(|c| c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-' || c == '_')
}

/// Windows' `canonicalize` returns `\\?\C:\…`, which cargo paths reject.
fn strip_verbatim(path: &Path) -> PathBuf {
    let text = path.to_string_lossy();
    PathBuf::from(text.strip_prefix(r"\\?\").unwrap_or(&text).to_string())
}

