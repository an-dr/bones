use super::*;

fn request(kind: Kind) -> Request {
    Request {
        name: "pong".to_string(),
        kind,
        dependencies: Dependencies::tagged("v3.1.0", "1.3.0"),
        source: None,
        pin: "v3.1.0".to_string(),
        created: false,
        vendored: None,
        cli: "C:/tools/bones-develop.exe".to_string(),
    }
}

#[test]
fn every_placeholder_is_filled_in_every_kind() {
    for kind in [Kind::Game, Kind::Egui, Kind::Web, Kind::Embed] {
        for (path, contents) in files(&request(kind)) {
            // `{{` alone is ordinary Rust inside format!; a placeholder is a
            // lowercase word between double braces.
            for placeholder in [
                "{{name}}",
                "{{sdk_dep}}",
                "{{test_dep}}",
                "{{kernel_dep}}",
                "{{kind_config}}",
                "{{app_member}}",
            ] {
                assert!(
                    !contents.contains(placeholder),
                    "{kind:?} {path} keeps {placeholder}"
                );
            }
        }
    }
}

#[test]
fn only_embed_has_an_app_and_names_it_a_member() {
    let embed = files(&request(Kind::Embed));
    assert!(embed.iter().any(|(path, _)| *path == "app/src/main.rs"));
    let workspace = &embed
        .iter()
        .find(|(path, _)| *path == "Cargo.toml")
        .unwrap()
        .1;
    assert!(workspace.contains("\"app\""));

    let game = files(&request(Kind::Game));
    assert!(!game.iter().any(|(path, _)| path.starts_with("app/")));
}

#[test]
fn the_web_kind_turns_web_panels_on() {
    let web = files(&request(Kind::Web));
    let config = &web
        .iter()
        .find(|(path, _)| *path == "bones.toml")
        .unwrap()
        .1;
    assert!(config.contains("web = true"));
}

#[test]
fn names_must_work_as_crate_and_extension_names() {
    assert!(is_crate_name("pong"));
    assert!(is_crate_name("pong-2_d"));
    assert!(!is_crate_name("Pong"));
    assert!(!is_crate_name("2pong"));
    assert!(!is_crate_name("my pong"));
}

#[test]
fn a_verbatim_windows_path_is_stripped() {
    assert_eq!(
        strip_verbatim(Path::new(r"\\?\C:\code\bones")),
        PathBuf::from(r"C:\code\bones")
    );
}

#[test]
fn the_mcp_config_names_the_cli_that_wrote_it() {
    let files = files(&request(Kind::Game));
    let mcp = &files
        .iter()
        .find(|(path, _)| *path == ".mcp.json")
        .unwrap()
        .1;
    assert!(mcp.contains("C:/tools/bones-develop.exe"), "{mcp}");
}

#[test]
fn agents_md_is_the_plugin_rules_with_their_source() {
    let files = files(&request(Kind::Game));
    let agents = &files
        .iter()
        .find(|(path, _)| *path == "AGENTS.md")
        .unwrap()
        .1;
    assert!(agents.starts_with("<!-- Generated by bones-develop from the bones-user agent plugin"));
    assert!(agents.ends_with(RULES));
}

#[test]
fn the_project_mcp_config_is_the_plugin_server_in_project_form() {
    let mcp: serde_json::Value =
        serde_json::from_str(&project_mcp(PLUGIN_MCP, "C:/x/bones-develop.exe")).unwrap();
    assert!(mcp.get("$schema").is_none());
    assert_eq!(
        mcp["mcpServers"]["bones"]["command"],
        "C:/x/bones-develop.exe"
    );
    assert_eq!(mcp["mcpServers"]["bones"]["args"][0], "mcp");
}

#[test]
fn an_older_tags_bones_cli_command_becomes_this_tool() {
    let old = r#"{ "mcpServers": { "bones": { "type": "stdio", "command": "bones-cli", "args": ["mcp"] } } }"#;
    let mcp: serde_json::Value =
        serde_json::from_str(&project_mcp(old, "C:/x/bones-develop.exe")).unwrap();
    assert_eq!(
        mcp["mcpServers"]["bones"]["command"],
        "C:/x/bones-develop.exe"
    );
}

#[test]
fn the_newest_tag_skips_pre_releases_and_other_names() {
    let tags = ["v3.1.0", "v3.2.0", "v3.3.0-rc.1", "vci"]
        .map(String::from)
        .to_vec();
    assert_eq!(newest_release(tags).as_deref(), Some("v3.2.0"));
    assert_eq!(newest_release(vec!["vci".into()]), None);
}

#[test]
fn a_submodule_is_excluded_from_the_project_workspace() {
    let workspace = "[workspace]\nmembers = [\"extension\", \"checks\"]\n";
    assert_eq!(excluding(workspace, None), workspace);
    assert_eq!(
        excluding(workspace, Some(r"vendor\bones")),
        "[workspace]\nmembers = [\"extension\", \"checks\"]\nexclude = [\"vendor/bones\"]\n"
    );
}
