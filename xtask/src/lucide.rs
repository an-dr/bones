//! `cargo xtask lucide <package>`: brings a Lucide release into bones
//! (ADR-049) from an unpacked `lucide-static` npm package.
//!
//! - Copies `font/lucide.ttf` and the licence beside the ui module, which
//!   embeds the font as a fallback so icons render inside any text.
//! - Regenerates `bones-messages`' `ui::icons`: one constant per icon,
//!   holding its glyph, and a by-name table for trees that name icons.
//!
//! Get the package with `npm pack lucide-static` and unpack the tarball;
//! pass the folder holding `package.json`.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use crate::process::repo_root;
use crate::Result;

pub fn run(args: &[String]) -> Result {
    let [package] = args else {
        return Err("usage: cargo xtask lucide <unpacked lucide-static package>".to_string());
    };
    let package = Path::new(package);
    let read =
        |path: &str| std::fs::read(package.join(path)).map_err(|e| format!("reading {path}: {e}"));
    let manifest: serde_json::Value =
        serde_json::from_slice(&read("package.json")?).map_err(|e| format!("package.json: {e}"))?;
    let version = manifest["version"]
        .as_str()
        .unwrap_or("unknown")
        .to_string();
    let codepoints: BTreeMap<String, u32> = serde_json::from_slice(&read("font/codepoints.json")?)
        .map_err(|e| format!("font/codepoints.json: {e}"))?;

    let root = repo_root();
    let assets = root.join("crates/bones-kernel/bones-module-ui/assets");
    std::fs::create_dir_all(&assets).map_err(|e| e.to_string())?;
    std::fs::write(assets.join("lucide.ttf"), read("font/lucide.ttf")?)
        .map_err(|e| e.to_string())?;
    std::fs::write(assets.join("LICENSE-lucide"), read("LICENSE")?).map_err(|e| e.to_string())?;

    let icons = root.join("crates/bones-messages/src/ui/icons.rs");
    std::fs::write(&icons, generate(&version, &codepoints)).map_err(|e| e.to_string())?;
    println!(
        "Lucide {version}: {} icons; wrote the font, its licence, and {}.",
        codepoints.len(),
        icons.display()
    );
    Ok(())
}

/// The `ui::icons` module for `codepoints` (name to code point).
fn generate(version: &str, codepoints: &BTreeMap<String, u32>) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "//! Lucide {version} icons (ISC licence), generated by `cargo xtask lucide`; do not edit.\n\
         //!\n\
         //! - Each constant is the icon's glyph as text: put it in any widget's text,\n\
         //!   e.g. `format!(\"{{}} Delete\", icons::TRASH_2)`. The ui module draws it with\n\
         //!   the bundled Lucide font.\n\
         //! - Names follow lucide.dev, upper-cased with `_` for `-`.\n\
         //! - `by_name` finds a glyph by its lucide.dev name, for the `icon` kind.\n"
    );
    for (name, code) in codepoints {
        let _ = writeln!(out, "/// Lucide `{name}`.");
        let _ = writeln!(
            out,
            "pub const {}: &str = \"\\u{{{code:x}}}\";",
            constant(name)
        );
    }
    let _ = writeln!(
        out,
        "\n/// Every icon by its lucide.dev name, sorted for binary search."
    );
    let _ = writeln!(out, "const BY_NAME: &[(&str, &str)] = &[");
    for name in codepoints.keys() {
        let _ = writeln!(out, "    (\"{name}\", {}),", constant(name));
    }
    let _ = writeln!(out, "];");
    let _ = writeln!(
        out,
        "\n/// The glyph of the icon lucide.dev calls `name`, e.g. `\"trash-2\"`.\n\
         pub fn by_name(name: &str) -> Option<&'static str> {{\n    \
         BY_NAME\n        .binary_search_by(|(known, _)| (*known).cmp(name))\n        \
         .ok()\n        .map(|index| BY_NAME[index].1)\n}}"
    );
    out
}

/// `trash-2` becomes `TRASH_2`; a leading digit gets an `_`.
fn constant(name: &str) -> String {
    let upper = name.replace('-', "_").to_uppercase();
    match upper.chars().next() {
        Some(c) if c.is_ascii_digit() => format!("_{upper}"),
        _ => upper,
    }
}
