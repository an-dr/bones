//! `cargo xtask ts-codec`: regenerates `examples/extensions/ts-demo/src/
//! messages.ts` from `wit/wire-format.json` (ADR-041): a TypeScript type and
//! a field list for every core topic whose payload is a plain field list.
//!
//! The workspace tests regenerate it in memory and fail when the committed
//! file differs, so a TypeScript guest cannot fall behind the contract.

use std::path::Path;

use crate::files::write_file;
use crate::process::repo_root;
use crate::wire_format::model::{Entry, FieldType};
use crate::wire_format::{self, Spec};
use crate::Result;

/// Where the generated module lives, relative to the repository root.
pub const OUTPUT: &str = "examples/extensions/ts-demo/src/messages.ts";

/// The field types `wire.ts` encodes, with their TypeScript type.
const PRIMITIVES: [(&str, &str); 10] = [
    ("u8", "number"),
    ("u16", "number"),
    ("u32", "number"),
    ("i32", "number"),
    ("f32", "number"),
    ("bool", "boolean"),
    ("str", "string"),
    ("str-rest", "string"),
    ("blob", "Uint8Array"),
    ("rest", "Uint8Array"),
];

pub fn run(args: &[String]) -> Result {
    if !args.is_empty() {
        return Err("usage: cargo xtask ts-codec".to_string());
    }
    let root = repo_root();
    write_file(&root.join(OUTPUT), &generate(&root)?)?;
    println!("Written {OUTPUT}.");
    Ok(())
}

/// The module text for the specification under `root`.
pub fn generate(root: &Path) -> Result<String> {
    let topics = plain_topics(&wire_format::load(root)?);

    let mut out = String::from(
        "// Generated by `cargo xtask ts-codec` from wit/wire-format.json. Do not edit.\n\
         // One type and one field list per core topic whose payload is a plain\n\
         // field list; wire.ts encodes them.\n\n\
         import type { FieldType } from \"./wire.ts\";\n",
    );
    for (topic, fields) in &topics {
        out.push_str(&format!(
            "\n/** `{topic}` */\nexport interface {} {{\n",
            type_name(topic)
        ));
        for (name, ty) in fields {
            out.push_str(&format!("  {name}: {};\n", ts_type(ty)));
        }
        out.push_str("}\n");
    }
    out.push_str(
        "\n/** Every topic with a plain field list, by name. */\nexport interface Messages {\n",
    );
    for (topic, _) in &topics {
        out.push_str(&format!("  \"{topic}\": {};\n", type_name(topic)));
    }
    out.push_str(
        "}\n\n/** Each topic's fields, in payload order. */\n\
         export const FIELDS: { [T in keyof Messages]: ReadonlyArray<readonly [string, FieldType]> } = {\n",
    );
    for (topic, fields) in &topics {
        let list: Vec<String> = fields
            .iter()
            .map(|(name, ty)| format!("[\"{name}\", \"{ty}\"]"))
            .collect();
        out.push_str(&format!("  \"{topic}\": [{}],\n", list.join(", ")));
    }
    out.push_str("};\n");
    Ok(out)
}

/// `(topic, fields)` for each topic whose payload is primitives only, or
/// empty: no union, no list, and no defined shape.
fn plain_topics(spec: &Spec) -> Vec<(String, Vec<(String, String)>)> {
    spec.entries()
        .filter_map(|entry| Some((entry, plain_fields(entry)?)))
        .flat_map(|(entry, fields)| {
            entry
                .topics
                .iter()
                .map(move |topic| (topic.clone(), fields.clone()))
        })
        .collect()
}

fn plain_fields(entry: &Entry) -> Option<Vec<(String, String)>> {
    if entry.payload.union.is_some() {
        return None;
    }
    entry
        .payload
        .fields
        .iter()
        .map(|field| match &field.ty {
            FieldType::Named(ty) if PRIMITIVES.iter().any(|(p, _)| p == ty) => {
                Some((field.name.clone(), ty.clone()))
            }
            _ => None,
        })
        .collect()
}
/// `gfx/draw-rect` → `GfxDrawRect`.
fn type_name(topic: &str) -> String {
    topic
        .split(['/', '-'])
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                Some(first) => first.to_uppercase().chain(chars).collect(),
                None => String::new(),
            }
        })
        .collect()
}

fn ts_type(ty: &str) -> &'static str {
    PRIMITIVES
        .iter()
        .find(|(name, _)| *name == ty)
        .map(|(_, ts)| *ts)
        .unwrap_or("never")
}

