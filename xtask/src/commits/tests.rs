use super::find_violations;

#[test]
fn rejects_an_ai_co_author_trailer() {
    let message =
        "feat: add x\n\n- because\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>";
    assert_eq!(find_violations(message).len(), 1);
}

#[test]
fn rejects_co_author_trailers_case_insensitively() {
    assert_eq!(
        find_violations("co-authored-by: GitHub Copilot <x@y>").len(),
        1
    );
    assert_eq!(find_violations("CO-DEVELOPED-BY: ChatGPT").len(), 1);
}

#[test]
fn rejects_assistant_trailers_whoever_they_name() {
    assert_eq!(find_violations("Assisted-By: some tool").len(), 1);
    assert_eq!(find_violations("Generated-By: anything").len(), 1);
}

#[test]
fn rejects_generated_with_lines_naming_a_tool() {
    let message = "fix: y\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)";
    assert_eq!(find_violations(message).len(), 1);
}

#[test]
fn accepts_a_human_co_author() {
    let message = "feat: pair work\n\nCo-Authored-By: Jane Doe <jane@example.com>";
    assert!(find_violations(message).is_empty());
}

#[test]
fn accepts_a_tool_named_as_the_subject_of_the_work() {
    let message = "feat(install): link the skills into the Claude Code directory\n\n- copilot users need the same";
    assert!(find_violations(message).is_empty());
}

#[test]
fn accepts_generated_files_that_name_no_tool() {
    assert!(find_violations("- notices are generated by cargo metadata").is_empty());
}
