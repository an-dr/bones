//! `cargo xtask check-commits <git-log-args>`: fails when a commit message
//! credits an AI tool as an author.
//!
//! - What: rejects `Co-Authored-By:`-style trailers naming an AI tool,
//!   assistant trailers (`Assisted-By:`, `Generated-By:`, `Created-By:`)
//!   whoever they name, and "generated with `<tool>`" lines.
//! - Why: a trailer records who is accountable for a change -- the person
//!   who reviewed and committed it. The project is open about using AI; the
//!   tool is no more a co-author than the editor or the compiler.
//!
//! Naming a tool as the subject of the work stays allowed
//! (`feat: support claude code hooks`): only attribution is checked.

use std::process::Command;

use crate::process::{read_output, repo_root};
use crate::Result;

#[cfg(test)]
mod tests;

/// Trailers that credit a co-author: rejected when they name an AI tool.
const AUTHOR_TRAILERS: [&str; 3] = ["co-authored-by", "co-developed-by", "authored-by"];

/// Trailers that only ever credit tooling: rejected whoever they name.
const ASSISTANT_TRAILERS: [&str; 3] = ["assisted-by", "generated-by", "created-by"];

/// Lowercase fragments that identify an AI tool or its vendor address.
const AI_MARKERS: [&str; 13] = [
    "claude",
    "anthropic",
    "openai",
    "chatgpt",
    "gpt-",
    "copilot",
    "gemini",
    "codex",
    "cursor",
    "devin",
    "aider",
    "windsurf",
    "[bot]",
];

pub fn run(args: &[String]) -> Result {
    if args.is_empty() {
        return Err(
            "usage: cargo xtask check-commits <git-log-args>  (e.g. origin/main..HEAD)".to_string(),
        );
    }
    // Unit separator between hash and body, record separator between commits.
    let mut command = Command::new("git");
    command
        .current_dir(repo_root())
        .args(["log", "--format=%h%x1f%B%x1e"])
        .args(args);
    let log =
        read_output(&mut command).ok_or_else(|| format!("git log {} failed", args.join(" ")))?;

    let mut checked = 0;
    let mut offenders = Vec::new();
    for record in log.split('\x1e').map(str::trim).filter(|r| !r.is_empty()) {
        let (hash, message) = record.split_once('\x1f').unwrap_or((record, ""));
        checked += 1;
        for violation in find_violations(message) {
            offenders.push(format!("{hash}: {violation}"));
        }
    }
    if offenders.is_empty() {
        println!("{checked} commit(s) checked; none credits an AI tool.");
        return Ok(());
    }
    for offender in &offenders {
        println!("{offender}");
    }
    Err(format!(
        "{} line(s) credit an AI tool; the person committing is the author -- \
         remove the trailer (git commit --amend, or rebase for older commits)",
        offenders.len()
    ))
}

/// Every line of `message` that credits an AI tool, quoted for the report.
pub fn find_violations(message: &str) -> Vec<String> {
    message
        .lines()
        .map(str::trim)
        .filter(|line| credits_ai(line))
        .map(|line| format!("\"{line}\""))
        .collect()
}

fn credits_ai(line: &str) -> bool {
    let lower = line.to_lowercase();
    if let Some((key, value)) = lower.split_once(':') {
        let key = key.trim();
        if ASSISTANT_TRAILERS.contains(&key) {
            return true;
        }
        if AUTHOR_TRAILERS.contains(&key) {
            return names_ai(value);
        }
    }
    let generated = lower.contains("generated with") || lower.contains("generated by");
    (generated && names_ai(&lower)) || line.contains('\u{1F916}')
}

fn names_ai(text: &str) -> bool {
    AI_MARKERS.iter().any(|marker| text.contains(marker))
}
